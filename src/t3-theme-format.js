/**
 * The `:root` block for a theme imported from T3 Code: every --app-theme-*
 * role (its own colors, else T3's stock palette, or our token for the roles
 * above), T3's aliases under the --t3- prefix, and --radius / --font-sans.
 * `colors` were checked by sanitizeTheme.
 */
export const t3CompatCss = (colors, appearance) => {
  const stock = T3_STOCK_COLORS[appearance === 'light' ? 'light' : 'dark'];
  const lines = [];
  for (const role of T3_THEME_ROLES) {
    const token = T3_ROLE_TOKENS[role];
    const own = colors?.[role] ?? stock[role];
    lines.push(`${T3_ROLE_VARIABLES[role]}: ${token ? `var(--${token}, ${own})` : own};`);
  }
  for (const [name, value] of T3_ALIAS_VARIABLES) {
    lines.push(`--${T3_ALIAS_PREFIX}${name}: ${value.replace(/var\(--(?!app-theme-)([a-z0-9-]+)\)/g, `var(--${T3_ALIAS_PREFIX}$1)`)};`);
  }
  lines.push('--radius: var(--radius-lg);', '--font-sans: var(--font-ui);');
  return `:root {\n  ${lines.join('\n  ')}\n}`;
};
