/** Variable names an imported T3 theme's CSS gets renamed to (--x → --t3-x), so they never clash with ours (--accent, --warning…). */
export const T3_ALIAS_NAMES = Object.freeze(T3_ALIAS_VARIABLES.map(([name]) => name));
export const T3_ALIAS_PREFIX = 't3-';

/**
 * Roles that follow one of our tokens while an imported theme is on, so an
 * agent's later edit (a new accent) reaches the theme's own CSS too. The
 * import sets those tokens from the same roles, so nothing changes at first.
 */
