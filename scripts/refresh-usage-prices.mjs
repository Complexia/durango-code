// Rewrites src/main/usage-prices.js, the bundled snapshot of API list prices
// the Usage view estimates cost with (see src/main/usage-pricing.js).
//   node scripts/refresh-usage-prices.mjs
import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { USAGE_PRICES_URL, compactPriceCatalog } from '../src/main/usage-pricing.js';

const target = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/main/usage-prices.js');
const response = await fetch(USAGE_PRICES_URL);
if (!response.ok) throw new Error(`${USAGE_PRICES_URL}: HTTP ${response.status}`);
const catalog = compactPriceCatalog(await response.json());
const body = JSON.stringify(catalog, null, 1);
await fs.writeFile(
  target,
  `// Generated by scripts/refresh-usage-prices.mjs from ${USAGE_PRICES_URL}.\n// $ per million tokens. Do not edit by hand.\nexport default ${body};\n`
);
console.log(`Wrote ${Object.keys(catalog.models).length} model prices to ${path.relative(process.cwd(), target)}`);
